"""Streamlit interface for CodeMentor AI."""

from __future__ import annotations

import os

import streamlit as st
from dotenv import load_dotenv

from src.codementor.mentor import MentorConfigurationError, MentorRequestError, get_mentoring_response

load_dotenv()

st.set_page_config(
    page_title="CodeMentor AI",
    page_icon="🧑‍💻",
    layout="wide",
)

st.title("🧑‍💻 CodeMentor AI")
st.write(
    "A beginner-friendly coding mentor. Share a snippet and a question to get "
    "a clear explanation, debugging guidance, or a problem-solving hint."
)

with st.sidebar:
    st.header("Mentor settings")
    language = st.selectbox(
        "Programming language",
        ["Python", "JavaScript", "Java", "C", "C++", "SQL", "Other"],
    )
    help_mode = st.selectbox(
        "What do you need help with?",
        [
            "Explain an error",
            "Review my code",
            "Explain this code",
            "Give me a problem-solving hint",
        ],
    )
    st.caption("The response is generated by an AI model and may contain mistakes.")

code = st.text_area(
    "Your code",
    height=260,
    placeholder="Paste a small code snippet here...",
    help="Remove API keys, passwords, personal information, and confidential code before submitting.",
)
question = st.text_area(
    "What are you stuck on?",
    height=110,
    placeholder="Example: Explain this IndexError and show me how to fix it.",
)

st.warning(
    "Privacy: when you request help, your code and question are sent to Anthropic's API. "
    "Do not include secrets or code you are not permitted to share. API usage may incur charges."
)

if st.button("Help me understand", type="primary", use_container_width=True):
    if not code.strip():
        st.error("Enter a code snippet first.")
    elif not question.strip():
        st.error("Describe what you want help with.")
    else:
        api_key = os.getenv("ANTHROPIC_API_KEY", "").strip()
        model = os.getenv("ANTHROPIC_MODEL", "claude-sonnet-4-6").strip()

        if not api_key:
            st.error(
                "No API key was found. Add ANTHROPIC_API_KEY to your local .env file, "
                "then restart Streamlit. See the README for setup instructions."
            )
        else:
            with st.spinner("Reviewing your question..."):
                try:
                    response = get_mentoring_response(
                        api_key=api_key,
                        model=model,
                        language=language,
                        help_mode=help_mode,
                        code=code,
                        question=question,
                    )
                except MentorConfigurationError as exc:
                    st.error(str(exc))
                except MentorRequestError as exc:
                    st.error(str(exc))
                else:
                    st.subheader("Your explanation")
                    st.markdown(response)
                    st.caption("Review the suggestions and test any code changes before using them.")
